#!/usr/bin/env python3
"""Writes trained velocity-net weights as a C++ header.

python -m research.nets.export_weights vel_final.pt src/weights.hpp
"""
import sys

import torch


def export(weights, path):
    state = torch.load(weights, map_location="cpu")
    names = {"conv.0": "C0", "conv.2": "C1", "conv.4": "C2", "conv.6": "C3", "conv.8": "C4", "conv.10": "C5",
             "head.1": "L0", "head.3": "L1"}
    with open(path, "w") as f:
        f.write("// Generated by research/nets/export_weights.py. Do not edit.\n#pragma once\n")
        for key, tensor in state.items():
            layer, kind = key.rsplit(".", 1)
            values = tensor.numpy().ravel()  # row-major: (out, in, kernel) for conv, (out, in) for linear
            f.write(f"static const float {names[layer]}_{kind}[{len(values)}] = {{")
            f.write(",".join(f"{v:.9e}f" for v in values))
            f.write("};\n")


if __name__ == "__main__":
    export(sys.argv[1], sys.argv[2])
